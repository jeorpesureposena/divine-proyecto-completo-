// ─── Motor de traducción ───────────────────────────────────────────

function applyLanguage(lang) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['es'];

    // Traducir todos los elementos con data-i18n
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            if (el.tagName === 'INPUT' && el.hasAttribute('placeholder') && !el.hasAttribute('data-i18n-target')) {
                el.placeholder = dict[key];
            } else if (el.getAttribute('data-i18n-target') === 'placeholder') {
                el.placeholder = dict[key];
            } else {
                // If it contains HTML like <br />, use innerHTML, otherwise textContent
                if (dict[key].includes('<br')) {
                    el.innerHTML = dict[key];
                } else {
                    el.textContent = dict[key];
                }
            }
        }
    });

    // Marcar el idioma activo en los selectores de settings
    document.querySelectorAll('.lang-item').forEach(item => {
        const check = item.querySelector('.lang-check');
        if (!check) return;

        if (item.dataset.lang === lang) {
            // Activo: mostrar check azul
            check.className = 'lang-check w-7 h-7 bg-divine-blue rounded-full flex items-center justify-center';
            check.innerHTML = `<svg class="w-4 h-4 text-white" fill="none" stroke="currentColor" stroke-width="3" viewBox="0 0 24 24"><path d="M5 13l4 4L19 7" stroke-linecap="round" stroke-linejoin="round"/></svg>`;
            item.classList.add('border-divine-blue');
            item.classList.remove('border-slate-100');
        } else {
            // Inactivo: círculo vacío
            check.className = 'lang-check w-7 h-7 border-2 border-slate-200 rounded-full';
            check.innerHTML = '';
            item.classList.remove('border-divine-blue');
            item.classList.add('border-slate-100');
        }
    });
}

// ─── Selector de idioma (llamado desde settings-admin.html) ────────

function selectLang(el) {
    const lang = el.dataset.lang;
    if (!lang) return;

    // Guardar en localStorage (persiste entre páginas)
    localStorage.setItem('divine_lang', lang);

    // Aplicar inmediatamente
    applyLanguage(lang);
}
window.selectLang = selectLang;

// ─── Auto-aplicar al cargar cualquier página ───────────────────────

(function () {
    const saved = localStorage.getItem('divine_lang') || 'es';
    // Esperar al DOM
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', () => applyLanguage(saved));
    } else {
        applyLanguage(saved);
    }
})();

// ─── Utilidad para obtener textos en JavaScript ────────────────────
window.getTranslation = function(key) {
    const lang = localStorage.getItem('divine_lang') || 'es';
    const dict = TRANSLATIONS[lang] || TRANSLATIONS['es'];
    return dict[key] || TRANSLATIONS['es'][key] || key;
};
